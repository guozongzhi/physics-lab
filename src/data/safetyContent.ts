export function getSafetyQuestionsByCategory(category: SafetyCategory, allQuestions: Question[]): Question[] {
  return allQuestions.filter((q) => q.safetyCategory === category);
}

export function sampleExamQuestions(category: SafetyCategory, allQuestions: Question[], count = 10): Question[] {
  const pool = getSafetyQuestionsByCategory(category, allQuestions);
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
